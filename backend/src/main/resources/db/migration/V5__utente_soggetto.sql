-- =====================================================================
-- V5 - Assegnazione degli utenti ai soggetti NIS
--
-- Ogni riga dice che un utente (lo username di Keycloak) puo' lavorare su
-- un soggetto e con quale ruolo. E' la base dell'isolamento tra soggetti:
-- un utente vede e modifica solo i soggetti a cui e' assegnato.
-- L'amministratore della piattaforma e' un ruolo globale di Keycloak e non
-- compare qui.
--
-- Si usa lo username e non l'id interno di Keycloak perche' e' lo stesso
-- valore che i trigger registrano in LogEstrazione: audit e permessi parlano
-- della stessa persona. Nel realm nis2 lo username non e' modificabile.
-- =====================================================================

CREATE TABLE UtenteSoggetto (
    id                  NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    utente              VARCHAR2(64) NOT NULL,
    soggetto_nis_id     NUMBER(19) NOT NULL REFERENCES SoggettoNIS(id),
    ruolo               VARCHAR2(20) NOT NULL
                        CHECK (ruolo IN ('REFERENTE_NIS', 'OPERATORE', 'REVISORE')),
    data_assegnazione   TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    assegnato_da        VARCHAR2(64) NOT NULL,
    UNIQUE (utente, soggetto_nis_id)
);

CREATE INDEX idx_utentesoggetto_soggetto ON UtenteSoggetto (soggetto_nis_id);
