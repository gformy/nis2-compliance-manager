-- Organizzazione e valutazione del rischio (Appendice C)
MERGE INTO TipoDocumentoGovernance t
USING (SELECT 'GV.RR-02' AS codice, 'Organizzazione per la sicurezza informatica' AS nome FROM dual UNION ALL
       SELECT 'ID.RA-05', 'Valutazione del rischio per la sicurezza dei sistemi informativi e di rete' FROM dual) s
ON (t.codice = s.codice)
WHEN NOT MATCHED THEN INSERT (codice, nome) VALUES (s.codice, s.nome);

-- Politiche di sicurezza informatica, una per ambito (GV.PO-01 punto 1)
MERGE INTO TipoDocumentoGovernance t
USING (SELECT 'a' AS ambito, 'gestione del rischio' AS nome FROM dual UNION ALL
       SELECT 'b', 'ruoli e responsabilita''' FROM dual UNION ALL
       SELECT 'c', 'affidabilita'' delle risorse umane' FROM dual UNION ALL
       SELECT 'd', 'conformita'' e audit di sicurezza' FROM dual UNION ALL
       SELECT 'e', 'gestione dei rischi della catena di approvvigionamento' FROM dual UNION ALL
       SELECT 'f', 'gestione degli asset' FROM dual UNION ALL
       SELECT 'g', 'gestione delle vulnerabilita''' FROM dual UNION ALL
       SELECT 'h', 'continuita'' operativa, ripristino in caso di disastro e gestione delle crisi' FROM dual UNION ALL
       SELECT 'i', 'autenticazione, identita'' digitali e controllo accessi' FROM dual UNION ALL
       SELECT 'j', 'sicurezza fisica' FROM dual UNION ALL
       SELECT 'k', 'formazione del personale e consapevolezza' FROM dual UNION ALL
       SELECT 'l', 'sicurezza dei dati' FROM dual UNION ALL
       SELECT 'm', 'sviluppo, configurazione, manutenzione e dismissione dei sistemi' FROM dual UNION ALL
       SELECT 'n', 'protezione delle reti e delle comunicazioni' FROM dual UNION ALL
       SELECT 'o', 'monitoraggio degli eventi di sicurezza' FROM dual UNION ALL
       SELECT 'p', 'risposta agli incidenti e ripristino' FROM dual) s
ON (t.codice = 'GV.PO-01-' || s.ambito)
WHEN NOT MATCHED THEN
    INSERT (codice, nome, ambito_politica) VALUES ('GV.PO-01-' || s.ambito, 'Politica: ' || s.nome, s.ambito);

-- Politiche e documenti valgono per importanti ed essenziali (Allegati 1 e 2)
INSERT INTO DocumentoGovernanceApplicabilita (tipo_documento_id, tipo_soggetto_id)
SELECT td.id, ts.id
FROM TipoDocumentoGovernance td CROSS JOIN TipoSoggettoNIS ts
WHERE NOT EXISTS (SELECT 1 FROM DocumentoGovernanceApplicabilita a
                  WHERE a.tipo_documento_id = td.id AND a.tipo_soggetto_id = ts.id);

-- Un documento per tipo e soggetto; riesame almeno annuale (GV.PO-02 punto 1)
ALTER TABLE DocumentoGovernance ADD (
    periodicita_riesame_mesi NUMBER(2) DEFAULT 12 NOT NULL
                             CONSTRAINT ck_documento_periodicita CHECK (periodicita_riesame_mesi BETWEEN 1 AND 12),
    note                     VARCHAR2(500)
);
ALTER TABLE DocumentoGovernance ADD CONSTRAINT uq_documento_tipo UNIQUE (soggetto_nis_id, tipo_documento_id);
ALTER TABLE DocumentoGovernance ADD CONSTRAINT ck_documento_riesame
    CHECK (data_ultimo_riesame IS NULL OR data_approvazione IS NULL OR data_ultimo_riesame >= data_approvazione);

-- File dei documenti: ogni caricamento e' una nuova riga, mai modificata.
CREATE TABLE DocumentoGovernanceFile (
    id                  NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    documento_id        NUMBER(19) NOT NULL REFERENCES DocumentoGovernance(id),
    versione_documento  VARCHAR2(20),
    nome_file           VARCHAR2(255) NOT NULL,
    content_type        VARCHAR2(100) NOT NULL,
    dimensione          NUMBER(10) NOT NULL CONSTRAINT ck_file_dimensione CHECK (dimensione BETWEEN 1 AND 10485760),
    sha256              CHAR(64) NOT NULL,
    contenuto           BLOB NOT NULL,
    caricato_il         TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    caricato_da         VARCHAR2(64) DEFAULT NVL(SYS_CONTEXT('USERENV', 'CLIENT_IDENTIFIER'), USER) NOT NULL
);
CREATE INDEX idx_documento_file ON DocumentoGovernanceFile (documento_id, caricato_il);
