-- =====================================================================
-- V12 - Organizzazioni (clienti della piattaforma) e piani a soggetti
--
-- Un'organizzazione e' chi acquista il servizio: un cliente diretto o un
-- rivenditore (MSP, studio di consulenza) che gestisce i soggetti NIS dei
-- propri clienti. Ogni soggetto appartiene a una sola organizzazione.
--
-- Regole imposte dal database, oltre che dal backend:
--  * quota: un'organizzazione non supera il numero di soggetti del piano;
--  * isolamento: un utente che appartiene a un'organizzazione non puo' essere
--    assegnato a soggetti di un'altra organizzazione.
-- =====================================================================

CREATE TABLE PianoAbbonamento (
    id                          NUMBER(5) PRIMARY KEY,
    codice                      VARCHAR2(20) NOT NULL UNIQUE,
    nome                        VARCHAR2(100) NOT NULL,
    max_soggetti                NUMBER(5),          -- NULL = illimitato
    prezzo_mensile_soggetto     NUMBER(8,2) NOT NULL CHECK (prezzo_mensile_soggetto >= 0),
    in_vendita                  NUMBER(1) DEFAULT 1 NOT NULL CHECK (in_vendita IN (0, 1))
);

