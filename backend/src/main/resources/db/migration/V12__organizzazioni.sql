CREATE TABLE Organizzazione (
    id                      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome                    VARCHAR2(255) NOT NULL,
    codice_fiscale          VARCHAR2(16) NOT NULL UNIQUE,
    tipo                    VARCHAR2(20) NOT NULL
                            CONSTRAINT ck_organizzazione_tipo CHECK (tipo IN ('CLIENTE_DIRETTO', 'RIVENDITORE')),
    piano_id                NUMBER(5) NOT NULL REFERENCES PianoAbbonamento(id),
    stato                   VARCHAR2(10) DEFAULT 'ATTIVA' NOT NULL
                            CONSTRAINT ck_organizzazione_stato CHECK (stato IN ('ATTIVA', 'SOSPESA')),
    riferimento_contratto   VARCHAR2(100),
    data_contratto          DATE,
    logo                    BLOB,
    logo_content_type       VARCHAR2(20)
                            CONSTRAINT ck_organizzazione_logo CHECK (logo_content_type IN ('image/png', 'image/jpeg')),
    data_creazione          TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

