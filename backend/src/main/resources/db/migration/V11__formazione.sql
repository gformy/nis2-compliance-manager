-- =====================================================================
-- V11 - Formazione in materia di sicurezza informatica
--
-- PR.AT-01: piano di formazione del personale, inclusi gli organi di
--   amministrazione e direttivi, con contenuti e (eventuali) modalita' di
--   verifica; registro aggiornato di chi ha ricevuto la formazione e delle
--   verifiche svolte.
-- PR.AT-02: formazione dedicata ai ruoli specializzati, inclusi gli
--   amministratori di sistema.
--
-- Il piano in quanto documento (approvazione, riesame) resta il documento
-- di governance PR.AT-01 della V10; qui ci sono le attivita' e il registro.
-- Delle persone si tiene il minimo: nome, categoria e ruolo.
-- =====================================================================

INSERT INTO RegistroTabelle (id, nome_tabella) VALUES (11, 'PartecipazioneFormazione');

CREATE TABLE PersonaFormazione (
    id                  NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    soggetto_nis_id     NUMBER(19) NOT NULL REFERENCES SoggettoNIS(id),
    nome                VARCHAR2(255) NOT NULL,
    categoria           VARCHAR2(20) NOT NULL
                        CONSTRAINT ck_persona_categoria
                        CHECK (categoria IN ('ORGANO', 'RUOLO_SPECIALIZZATO', 'PERSONALE')),
    ruolo               VARCHAR2(100),
    data_cessazione     DATE,
    data_creazione      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);
CREATE INDEX idx_persona_formazione_soggetto ON PersonaFormazione (soggetto_nis_id);

CREATE TABLE AttivitaFormativa (
    id                  NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    soggetto_nis_id     NUMBER(19) NOT NULL REFERENCES SoggettoNIS(id),
    titolo              VARCHAR2(200) NOT NULL,
    contenuti           VARCHAR2(2000) NOT NULL,
    destinatari         VARCHAR2(20) NOT NULL
                        CONSTRAINT ck_attivita_destinatari
                        CHECK (destinatari IN ('TUTTI', 'ORGANO', 'RUOLO_SPECIALIZZATO')),
    data_prevista       DATE NOT NULL,
    durata_ore          NUMBER(5,1) CONSTRAINT ck_attivita_durata CHECK (durata_ore > 0),
    modalita_verifica   VARCHAR2(500),
    data_creazione      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);
CREATE INDEX idx_attivita_formativa_soggetto ON AttivitaFormativa (soggetto_nis_id, data_prevista);

-- Registro (PR.AT-01 punto 3, PR.AT-02 punto 2): solo aggiunte. Una verifica
-- non superata si ripete con una nuova riga in un'altra data.
CREATE TABLE PartecipazioneFormazione (
    id                  NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    attivita_id         NUMBER(19) NOT NULL REFERENCES AttivitaFormativa(id),
    persona_id          NUMBER(19) NOT NULL REFERENCES PersonaFormazione(id),
    data_svolgimento    DATE NOT NULL,
    esito_verifica      VARCHAR2(15) NOT NULL
                        CONSTRAINT ck_partecipazione_esito
                        CHECK (esito_verifica IN ('SUPERATA', 'NON_SUPERATA', 'NON_PREVISTA')),
    note                VARCHAR2(500),
    registrata_il       TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    registrata_da       VARCHAR2(64) DEFAULT NVL(SYS_CONTEXT('USERENV', 'CLIENT_IDENTIFIER'), USER) NOT NULL,
    CONSTRAINT uq_partecipazione UNIQUE (attivita_id, persona_id, data_svolgimento)
);
CREATE INDEX idx_partecipazione_persona ON PartecipazioneFormazione (persona_id, data_svolgimento);
