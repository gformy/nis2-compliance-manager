-- V10 - Politiche, piani e documenti approvati dagli organi di amministrazione
--
-- Il PW aveva gia' DocumentoGovernance (con storico di approvazione e riesame)
-- e un catalogo con i soli piani. Qui si completa il catalogo secondo:
--  * GV.PO-01 punto 1: politiche per gli ambiti a) - p);
--  * Linee guida ACN, Guida alla lettura, Appendice C: documenti da far
--    approvare agli organi di amministrazione e direttivi;
-- e si aggiungono i file dei documenti, conservati in Oracle.
