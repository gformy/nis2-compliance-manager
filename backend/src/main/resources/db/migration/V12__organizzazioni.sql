-- Amministratori di un'organizzazione: un utente appartiene al massimo a una organizzazione.
CREATE TABLE UtenteOrganizzazione (
    utente              VARCHAR2(64) PRIMARY KEY,
    organizzazione_id   NUMBER(19) NOT NULL REFERENCES Organizzazione(id),
    data_assegnazione   TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    assegnato_da        VARCHAR2(64) DEFAULT NVL(SYS_CONTEXT('USERENV', 'CLIENT_IDENTIFIER'), USER) NOT NULL
);
CREATE INDEX idx_utente_organizzazione ON UtenteOrganizzazione (organizzazione_id);

-- ---------------------------------------------------------------------
-- Quota: a fine istruzione si bloccano le organizzazioni toccate e si
-- ricontano i soggetti. Il blocco serializza due inserimenti concorrenti
-- nella stessa organizzazione: il secondo vede il primo e viene respinto.
-- ---------------------------------------------------------------------
CREATE OR REPLACE TRIGGER trg_quota_soggetti
FOR INSERT OR UPDATE OF organizzazione_id ON SoggettoNIS
COMPOUND TRIGGER
    TYPE t_ids IS TABLE OF NUMBER INDEX BY PLS_INTEGER;
    v_organizzazioni t_ids;

    AFTER EACH ROW IS
    BEGIN
        v_organizzazioni(:NEW.organizzazione_id) := :NEW.organizzazione_id;
    END AFTER EACH ROW;

    AFTER STATEMENT IS
        v_id      PLS_INTEGER;
        v_max     NUMBER;
        v_conta   NUMBER;
        v_bloccata NUMBER;
    BEGIN
        v_id := v_organizzazioni.FIRST;
        WHILE v_id IS NOT NULL LOOP
            SELECT o.id, p.max_soggetti INTO v_bloccata, v_max
            FROM Organizzazione o JOIN PianoAbbonamento p ON p.id = o.piano_id
            WHERE o.id = v_id
            FOR UPDATE OF o.id;
            IF v_max IS NOT NULL THEN
                SELECT COUNT(*) INTO v_conta FROM SoggettoNIS WHERE organizzazione_id = v_id;
                IF v_conta > v_max THEN
                    RAISE_APPLICATION_ERROR(-20010,
                        'Il piano dell''organizzazione consente al massimo ' || v_max || ' soggetti');
                END IF;
            END IF;
            v_id := v_organizzazioni.NEXT(v_id);
        END LOOP;
    END AFTER STATEMENT;
END trg_quota_soggetti;
/

-- Un piano piu' piccolo dei soggetti gia' presenti non si puo' assegnare.
CREATE OR REPLACE TRIGGER trg_quota_cambio_piano
BEFORE UPDATE OF piano_id ON Organizzazione
FOR EACH ROW
DECLARE
    v_max   NUMBER;
    v_conta NUMBER;
BEGIN
    SELECT max_soggetti INTO v_max FROM PianoAbbonamento WHERE id = :NEW.piano_id;
    IF v_max IS NOT NULL THEN
        SELECT COUNT(*) INTO v_conta FROM SoggettoNIS WHERE organizzazione_id = :NEW.id;
        IF v_conta > v_max THEN
            RAISE_APPLICATION_ERROR(-20010,
                'Il piano scelto consente al massimo ' || v_max || ' soggetti, l''organizzazione ne ha ' || v_conta);
        END IF;
    END IF;
END;
/

-- ---------------------------------------------------------------------
-- Isolamento: un utente di un'organizzazione lavora solo sui suoi soggetti.
-- ---------------------------------------------------------------------
CREATE OR REPLACE TRIGGER trg_assegnazione_stessa_organizzazione
BEFORE INSERT OR UPDATE ON UtenteSoggetto
FOR EACH ROW
DECLARE
    v_conta NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_conta
    FROM UtenteOrganizzazione uo JOIN SoggettoNIS s ON s.id = :NEW.soggetto_nis_id
    WHERE uo.utente = :NEW.utente AND uo.organizzazione_id <> s.organizzazione_id;
    IF v_conta > 0 THEN
        RAISE_APPLICATION_ERROR(-20011,
            'L''utente appartiene a un''altra organizzazione e non puo'' accedere a questo soggetto');
    END IF;
END;
/

CREATE OR REPLACE TRIGGER trg_membro_senza_soggetti_altrui
BEFORE INSERT OR UPDATE ON UtenteOrganizzazione
FOR EACH ROW
DECLARE
    v_conta NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_conta
    FROM UtenteSoggetto us JOIN SoggettoNIS s ON s.id = us.soggetto_nis_id
    WHERE us.utente = :NEW.utente AND s.organizzazione_id <> :NEW.organizzazione_id;
    IF v_conta > 0 THEN
        RAISE_APPLICATION_ERROR(-20011,
            'L''utente ha accesso a soggetti di un''altra organizzazione: revocarli prima');
    END IF;
END;
/
